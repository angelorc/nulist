-- Backfill: every existing row belongs to the "Default" organization.
DO $$
DECLARE
  org uuid;
  owner_id uuid;
BEGIN
  IF NOT (
    EXISTS (SELECT 1 FROM "user") OR EXISTS (SELECT 1 FROM "settings")
    OR EXISTS (SELECT 1 FROM "contacts") OR EXISTS (SELECT 1 FROM "lists")
    OR EXISTS (SELECT 1 FROM "topics") OR EXISTS (SELECT 1 FROM "segments")
    OR EXISTS (SELECT 1 FROM "suppressions") OR EXISTS (SELECT 1 FROM "imports")
    OR EXISTS (SELECT 1 FROM "templates") OR EXISTS (SELECT 1 FROM "files")
    OR EXISTS (SELECT 1 FROM "broadcasts") OR EXISTS (SELECT 1 FROM "messages")
    OR EXISTS (SELECT 1 FROM "webhook_endpoints") OR EXISTS (SELECT 1 FROM "audit_logs")
    OR EXISTS (SELECT 1 FROM "api_logs") OR EXISTS (SELECT 1 FROM "inbound_events")
  ) THEN
    -- Empty instance: the first sign-up creates the Default organization.
    RETURN;
  END IF;

  SELECT "id" INTO org FROM "organization" WHERE "slug" = 'default';
  IF org IS NULL THEN
    INSERT INTO "organization" ("name", "slug", "created_at")
    VALUES ('Default', 'default', now())
    RETURNING "id" INTO org;
  END IF;

  -- The first instance admin (else the oldest user) owns it; other admins administer it;
  -- members keep their current access as editors.
  SELECT "id" INTO owner_id FROM "user"
  ORDER BY ("role" = 'admin') DESC NULLS LAST, "created_at", "id"
  LIMIT 1;

  INSERT INTO "member" ("organization_id", "user_id", "role", "created_at")
  SELECT org, u."id",
    CASE
      WHEN u."id" = owner_id THEN 'owner'
      WHEN u."role" = 'admin' THEN 'admin'
      ELSE 'editor'
    END,
    now()
  FROM "user" u
  ON CONFLICT ("organization_id", "user_id") DO NOTHING;

  UPDATE "settings" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "contacts" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "lists" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "topics" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "segments" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "suppressions" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "imports" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "templates" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "files" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "broadcasts" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "messages" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "email_events" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "webhook_endpoints" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "webhook_deliveries" d SET "organization_id" = e."organization_id"
  FROM "webhook_endpoints" e
  WHERE e."id" = d."endpoint_id" AND d."organization_id" IS NULL;
  -- Before this migration the instance had a single tenant: its logs belong to it,
  -- except SNS subscription confirmations, which are instance-level.
  UPDATE "inbound_events" SET "organization_id" = org
  WHERE "organization_id" IS NULL AND "type" <> 'SubscriptionConfirmation';
  UPDATE "audit_logs" SET "organization_id" = org WHERE "organization_id" IS NULL;
  UPDATE "api_logs" SET "organization_id" = org WHERE "organization_id" IS NULL;

  -- API keys become organization-owned (apiKey({ references: 'organization' })): keep the
  -- creating user in metadata.createdBy and store the permissions of the key's scope preset
  -- (shared/auth/permissions.ts API_KEY_SCOPES). Metadata may be double-encoded JSON text.
  WITH decoded AS (
    SELECT "id", "reference_id",
      CASE
        WHEN "metadata" IS NULL OR "metadata" = '' THEN '{}'::jsonb
        WHEN jsonb_typeof("metadata"::jsonb) = 'string' THEN ("metadata"::jsonb #>> '{}')::jsonb
        ELSE "metadata"::jsonb
      END AS meta
    FROM "apikey"
    WHERE "reference_id" <> org::text
  )
  UPDATE "apikey" k SET
    "metadata" = (d.meta || jsonb_build_object('createdBy', d."reference_id"))::text,
    "permissions" = COALESCE(k."permissions", CASE
      WHEN d.meta ->> 'scope' = 'sending' THEN '{"transactional":["read","send"]}'
      ELSE '{"contact":["create","read","update","delete","import","export"],"list":["create","read","update","delete"],"segment":["read"],"topic":["read"],"template":["read"],"broadcast":["create","read","update","delete","send"],"transactional":["read","send"],"suppression":["read"]}'
    END),
    "reference_id" = org::text
  FROM decoded d
  WHERE k."id" = d."id";

  UPDATE "session" SET "active_organization_id" = org::text WHERE "active_organization_id" IS NULL;
END $$;--> statement-breakpoint
